/* Synthetic ProjectWorkbench interaction test; no GPU or production data. */
const { chromium } = require(process.env.REPAIR_SCOPE_PLAYWRIGHT || 'playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const base = process.env.REPAIR_SCOPE_TEST_URL || 'http://127.0.0.1:5179'
const output = path.resolve(__dirname, '../../var-test/repair-scope')
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.REPAIR_SCOPE_CHROME ? { executablePath: process.env.REPAIR_SCOPE_CHROME } : {}) })
  try {
    const page = await browser.newPage({ viewport: { width: 1000, height: 904 } })
    page.setDefaultTimeout(15000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${base}/tests/page-navigation-browser.html`)
    await page.getByLabel('圖片寬度').fill('400'); await page.getByLabel('圖片高度').fill('500')
    await page.getByLabel('真實頁面').setInputFiles([path.join(output, '01.png'), path.join(output, '02.png')])
    const toggle = page.getByRole('checkbox', { name: '限定修復範圍' })
    await toggle.waitFor(); assert.equal(await toggle.isChecked(), false)
    assert.equal(await page.getByRole('slider', { name: '左作用範圍線', exact: true }).count(), 0)
    await toggle.check()
    const line = edge => page.getByRole('slider', { name: `${edge}作用範圍線`, exact: true })
    const saved = () => page.waitForFunction(() => document.querySelector('.repair-scope-toolbar [role="status"]')?.textContent === '已保存')
    await line('左').waitFor({ state: 'attached' }); await saved()
    assert.equal(await line('左').getAttribute('aria-valuenow'), '10')
    assert.equal(await line('上').getAttribute('aria-valuenow'), '10')
    assert.equal(await line('右').getAttribute('aria-valuenow'), '390')
    assert.equal(await line('下').getAttribute('aria-valuenow'), '490')
    assert.equal(await page.locator('.edit-control-panel .repair-scope-toolbar').count(), 1)
    await page.waitForFunction(() => document.querySelector('.canvas-panels')?.getAttribute('aria-busy') === 'false')
    await page.getByLabel('修復作用範圍四條線').scrollIntoViewIfNeeded()
    const svg = await page.getByLabel('修復作用範圍四條線').boundingBox()
    await page.mouse.move(svg.x + svg.width * .025, svg.y + svg.height * .5)
    await page.mouse.down(); await page.mouse.move(svg.x + svg.width * .1, svg.y + svg.height * .5, { steps: 8 }); await page.mouse.up()
    await saved(); assert.equal(await line('左').getAttribute('aria-valuenow'), '40')
    await line('左').focus(); await page.keyboard.press('ArrowRight'); await saved()
    assert.equal(await line('左').getAttribute('aria-valuenow'), '41')
    // A different custom range on page 2 must be overwritten by Apply All.
    await page.getByRole('button', { name: '下一頁', exact: true }).click()
    await line('左').waitFor({ state: 'attached' }); assert.equal(await line('左').getAttribute('aria-valuenow'), '10')
    await line('左').focus(); await page.keyboard.press('ArrowRight'); await saved()
    await page.getByRole('button', { name: '上一頁', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[aria-label="左作用範圍線"]')?.getAttribute('aria-valuenow') === '41')
    await page.getByRole('button', { name: '將此範圍套用全部頁', exact: true }).click(); await saved()
    await page.getByRole('button', { name: '下一頁', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[aria-label="左作用範圍線"]')?.getAttribute('aria-valuenow') === '41')
    await page.getByRole('button', { name: '本頁改為整張圖', exact: true }).click(); await saved()
    assert.equal(await line('左').getAttribute('aria-valuenow'), '0')
    assert.equal(await line('右').getAttribute('aria-valuenow'), '400')
    await page.getByRole('button', { name: '上一頁', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[aria-label="左作用範圍線"]')?.getAttribute('aria-valuenow') === '41')
    // Save failure blocks page navigation and preserves the editable rectangle.
    await page.evaluate(() => {
      const previous = window.fetch
      window.fetch = (input, init) => String(input).endsWith('/repair-scope') ? Promise.resolve(new Response(JSON.stringify({ detail: 'scope test save failure' }), { status: 500, headers: { 'Content-Type': 'application/json' } })) : previous(input, init)
      window.__restoreScopeFetch = () => { window.fetch = previous }
    })
    await line('左').focus(); await page.keyboard.press('ArrowRight')
    await page.getByRole('button', { name: '下一頁', exact: true }).click()
    await page.getByText('scope test save failure', { exact: true }).waitFor()
    assert.equal(await line('左').getAttribute('aria-valuenow'), '42')
    await page.evaluate(() => window.__restoreScopeFetch())
    await page.getByRole('button', { name: '重試保存', exact: true }).click(); await saved()
    await page.screenshot({ path: path.join(output, 'four-lines.png'), fullPage: true })
    await toggle.uncheck(); await saved()
    assert.equal(await line('左').count(), 0)
    await page.getByRole('button', { name: '下一頁', exact: true }).click()
    assert.equal(await toggle.isChecked(), false)
    const requests = await page.evaluate(() => window.__pageNavigationFixture.requests())
    assert.equal(requests.filter(r => r.kind === 'save').length, 0, 'line changes must not edit image layers')
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ ok: true, checks: ['default off', 'four-line drag', 'keyboard pixel move', 'page save', 'overwrite customized page', 'whole page only affects current', 'save failure blocks navigation', 'retry', 'global disable', 'image layers unchanged'], screenshot: path.join(output, 'four-lines.png') }))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
