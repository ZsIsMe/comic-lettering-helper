/* Synthetic ProjectWorkbench interaction test; no GPU or production data. */
const { chromium } = require(process.env.REPAIR_SCOPE_PLAYWRIGHT || 'playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const base = process.env.REPAIR_SCOPE_TEST_URL || 'http://127.0.0.1:5179'
const output = path.resolve(__dirname, '../../var-test/repair-scope')
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.REPAIR_SCOPE_CHROME ? { executablePath: process.env.REPAIR_SCOPE_CHROME } : {}) })
  try {
    const page = await browser.newPage({ viewport: { width: 1300, height: 1700 } })
    page.setDefaultTimeout(15000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${base}/tests/page-navigation-browser.html`)
    await page.getByLabel('圖片寬度').fill('400'); await page.getByLabel('圖片高度').fill('500')
    await page.getByLabel('真實頁面').setInputFiles([path.join(output, '01.png'), path.join(output, '02.png')])
    const toggle = page.getByRole('checkbox', { name: '限定修復範圍' })
    const crop = page.getByRole('button', { name: 'F3 裁切', exact: true })
    const line = (axis, i) => page.getByRole('slider', { name: `${axis}分割線 ${i}`, exact: true }).first()
    const saved = () => page.waitForFunction(() => document.querySelector('.repair-scope-toolbar [role="status"]')?.textContent === '已保存')
    const ready = () => page.waitForFunction(() => document.querySelector('.canvas-panels')?.getAttribute('aria-busy') === 'false')
    const svg = () => page.getByLabel('裁切分割編輯區', { exact: true }).first()
    const click = async (x, y) => { const b = await svg().boundingBox(); await page.mouse.click(b.x + b.width * x / 400, b.y + b.height * y / 500) }
    const drag = async (x, y, nx, ny) => { const b = await svg().boundingBox(); await page.mouse.move(b.x + b.width * x / 400, b.y + b.height * y / 500); await page.mouse.down(); await page.mouse.move(b.x + b.width * nx / 400, b.y + b.height * ny / 500, { steps: 10 }); await page.mouse.up(); await saved() }
    await toggle.waitFor(); await ready(); assert.equal(await toggle.isChecked(), false)
    await toggle.check(); await saved()
    assert.equal(await line('垂直', 1).count(), 0, 'enabled differs from editing')
    await crop.click(); await svg().waitFor()
    assert.equal(await crop.getAttribute('aria-pressed'), 'true')
    assert.equal(await page.getByRole('button', { name: 'F1 純色填充', exact: true }).getAttribute('aria-pressed'), 'false')
    assert.equal(await line('垂直', 1).getAttribute('aria-valuenow'), '10')
    assert.equal(await svg().locator('[data-testid="repair-scope-cell"]').count(), 1)
    // At a low zoom the ten-pixel default guide overlaps the edge ruler; the line still receives pointer hits.
    await page.getByLabel('縮放百分比', { exact: true }).fill('20')
    assert.equal(await svg().evaluate(n => { const b = n.getBoundingClientRect(); return document.elementFromPoint(b.left + b.width * 10 / 400, b.top + b.height / 2)?.getAttribute('role') }), 'slider')
    await page.getByLabel('縮放百分比', { exact: true }).fill('100')
    await drag(1, 250, 150, 250); await drag(250, 1, 250, 200)
    assert.equal(await svg().locator('[data-testid="repair-scope-cell"]').count(), 0)
    await click(75, 100); await click(270, 350); await saved()
    assert.equal(await page.locator('.repair-scope-overlay [data-testid="repair-scope-cell"]').count(), 4)
    assert.equal(await svg().getByText('140 × 190 px', { exact: true }).count(), 1)
    assert.equal(await svg().getByText('240 × 290 px', { exact: true }).count(), 1)
    await drag(150, 100, 180, 100)
    await line('垂直', 2).focus(); await page.keyboard.press('ArrowRight'); await saved()
    assert.equal(await line('垂直', 2).getAttribute('aria-valuenow'), '181')
    assert.equal(await svg().getByText('171 × 190 px', { exact: true }).count(), 1)
    await page.getByRole('button', { name: '將此範圍套用全部頁', exact: true }).click(); await saved()
    await page.getByRole('button', { name: '下一頁', exact: true }).click(); await ready()
    assert.equal(await crop.getAttribute('aria-pressed'), 'true')
    assert.equal(await line('垂直', 2).getAttribute('aria-valuenow'), '181')
    await page.getByRole('button', { name: '本頁改為整張圖', exact: true }).click(); await saved()
    assert.equal(await svg().getByText('400 × 500 px', { exact: true }).count(), 1)
    await page.getByRole('button', { name: '取消點亮', exact: true }).click(); await saved()
    assert.equal(await svg().locator('[data-testid="repair-scope-cell"]').count(), 0)
    await click(200, 250); await saved(); assert.equal(await svg().locator('[data-testid="repair-scope-cell"]').count(), 1)
    await page.getByRole('button', { name: '上一頁', exact: true }).click(); await ready(); await crop.click()
    assert.equal(await line('垂直', 2).getAttribute('aria-valuenow'), '181')
    await page.evaluate(() => {
      const previous = window.fetch
      window.fetch = (input, init) => String(input).endsWith('/repair-scope') ? Promise.resolve(new Response(JSON.stringify({ detail: 'scope test save failure' }), { status: 500, headers: { 'Content-Type': 'application/json' } })) : previous(input, init)
      window.__restoreScopeFetch = () => { window.fetch = previous }
    })
    await line('垂直', 2).focus(); await page.keyboard.press('ArrowRight')
    await page.getByRole('button', { name: '下一頁', exact: true }).click()
    await page.getByText('scope test save failure', { exact: true }).waitFor()
    assert.equal(await line('垂直', 2).getAttribute('aria-valuenow'), '182')
    await page.evaluate(() => window.__restoreScopeFetch())
    await page.getByRole('button', { name: '重試保存', exact: true }).click(); await saved()
    const scopeRequests = await page.evaluate(() => window.__pageNavigationFixture.requests())
    assert.equal(scopeRequests.filter(r => r.kind === 'save').length, 0)
    await page.mouse.move(20, 20)
    await page.waitForFunction(() => !document.querySelector('.ant-tooltip:not(.ant-tooltip-hidden)'))
    await page.screenshot({ path: path.join(output, 'multi-crop.png'), fullPage: true })
    await svg().focus(); await page.keyboard.press('F2')
    assert.equal(await crop.getAttribute('aria-pressed'), 'false'); assert.equal(await toggle.isChecked(), true)
    assert.equal(await line('垂直', 2).count(), 0)
    const scopeCount = scopeRequests.filter(r => r.kind === 'scope-save').length
    await page.getByRole('button', { name: /矩\s*形/, exact: true }).click()
    const b = await page.locator('canvas[aria-label="Mask / 原圖"]').boundingBox()
    await page.mouse.move(b.x + b.width * .5, b.y + b.height * .5); await page.mouse.down(); await page.mouse.move(b.x + b.width * .55, b.y + b.height * .55); await page.mouse.up()
    await page.waitForFunction(() => window.__pageNavigationFixture.requests().some(r => r.kind === 'save'))
    for (const name of ['F1 純色填充', 'F2 待修補', 'F3 裁切']) {
      await page.getByRole('button', { name, exact: true }).click()
      await page.getByRole('button', { name: '下一頁', exact: true }).click(); await ready()
      assert.equal(await page.getByRole('button', { name, exact: true }).getAttribute('aria-pressed'), 'true', `${name} persists on next page`)
      await page.getByRole('button', { name: '上一頁', exact: true }).click(); await ready()
      assert.equal(await page.getByRole('button', { name, exact: true }).getAttribute('aria-pressed'), 'true', `${name} persists on previous page`)
    }
    const requests = await page.evaluate(() => window.__pageNavigationFixture.requests())
    assert.equal(requests.filter(r => r.kind === 'scope-save').length, scopeCount)
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ ok: true, checks: ['enable separate from crop', 'four-edge creation', 'multiple cells', 'synchronized dimensions', 'drag and keyboard', 'apply all and navigation', 'F1/F2/F3 survive page changes', 'full-page and empty selection', 'save failure guard', 'F2 exits and permits Mask edit'], screenshot: path.join(output, 'multi-crop.png') }))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
